export function calculateRank(points: number, isGiantsChosen = false): RankTitle {
  if (isGiantsChosen) return 'Giant’s Chosen';
  let current: RankTitle = 'Wanderer';
  for (const tier of RANKS) {
    if (tier.minPoints !== null && points >= tier.minPoints) {
      current = tier.title;
    }
  }
  return current;
}

export function getNextRankProgress(points: number, isGiantsChosen = false) {
  const currentTitle = calculateRank(points, isGiantsChosen);
  const currentIndex = RANKS.findIndex((r) => r.title === currentTitle);
  const currentTier = RANKS[currentIndex] ?? RANKS[0];
  const nextTier = RANKS[currentIndex + 1];

  if (!nextTier || nextTier.minPoints === null) {
    return {
      currentTier,
      nextTier: nextTier ?? null,
      progressPercent: 100,
      pointsToNext: 0,
    };
  }

  const floor = currentTier.minPoints ?? 0;
  const span = Math.max(1, nextTier.minPoints - floor);
  const earnedInTier = Math.max(0, points - floor);
  const progressPercent = Math.min(100, Math.round((earnedInTier / span) * 100));

  return {
    currentTier,
    nextTier,
    progressPercent,
    pointsToNext: Math.max(0, nextTier.minPoints - points),
  };
}

